-- Test-mode collection reservations. No existing invoice is enrolled or queued.
CREATE TABLE IF NOT EXISTS autopay_collections (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 document_type ENUM('invoice','project_invoice') NOT NULL,
 document_id INT NOT NULL,
 authorization_id BIGINT UNSIGNED NOT NULL,
 client_id INT NOT NULL,
 amount_cents BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL,
 processor_account_id VARCHAR(255) NOT NULL,
 installation_id VARCHAR(64) NOT NULL,
 stripe_customer_id VARCHAR(255) NOT NULL,
 payment_method_id VARCHAR(255) NOT NULL,
 method_type VARCHAR(32) NOT NULL,
 idempotency_key VARCHAR(255) NOT NULL,
 stripe_payment_intent_id VARCHAR(255) NULL,
 state ENUM('pending','processing','requires_action','failed','succeeded','held') NOT NULL DEFAULT 'pending',
 financial_hold TINYINT(1) NOT NULL DEFAULT 0,
 attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
 first_attempt_at DATETIME NULL,
 next_attempt_at DATETIME NULL,
 lease_token CHAR(32) NULL,
 lease_until DATETIME NULL,
 last_event_created BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_error VARCHAR(255) NULL,
 source VARCHAR(50) NOT NULL,
 created_by INT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_autopay_document(document_type,document_id),
 UNIQUE KEY uq_autopay_idempotency(idempotency_key),
 UNIQUE KEY uq_autopay_intent(stripe_payment_intent_id),
 KEY ix_autopay_worker(state,next_attempt_at,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
