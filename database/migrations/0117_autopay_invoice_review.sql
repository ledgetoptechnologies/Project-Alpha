CREATE TABLE IF NOT EXISTS autopay_invoice_reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 collection_id BIGINT UNSIGNED NOT NULL,
 document_type ENUM('invoice','project_invoice') NOT NULL,
 document_public_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 client_public_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 generation CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 management_token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 basis_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision_number INT NOT NULL,
 amount_cents BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL,
 due_date DATE NULL,
 timezone VARCHAR(64) NOT NULL,
 recipient VARCHAR(255) NOT NULL,
 status ENUM('awaiting_delivery','scheduled','superseded','skipped','question','held') NOT NULL DEFAULT 'awaiting_delivery',
 delivered_at DATETIME NULL,
 scheduled_at DATETIME NULL,
 delivery_log_id BIGINT UNSIGNED NULL,
 question_text VARCHAR(2000) NULL,
 resolution_text VARCHAR(2000) NULL,
 resolved_by INT NULL,
 resolved_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_autopay_review_generation(generation),
 UNIQUE KEY uq_autopay_review_token(management_token),
 KEY ix_autopay_review_collection(collection_id,id),
 KEY ix_autopay_review_document(document_type,document_public_id,id),
 CONSTRAINT fk_autopay_review_collection FOREIGN KEY(collection_id) REFERENCES autopay_collections(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
